package resolver

import (
	"encoding/json"
	"fmt"
	"strings"
	"testing"
)

// ---------- helpers to build synthetic lock file data ----------

func buildPackageLockJSON(n int) []byte {
	pkgs := make(map[string]any, n+1)
	pkgs[""] = map[string]string{"name": "root"}
	for i := range n {
		pkgs[fmt.Sprintf("node_modules/pkg-%d", i)] = map[string]string{
			"version":   fmt.Sprintf("%d.%d.%d", i%10, i%100, i),
			"resolved":  fmt.Sprintf("https://registry.npmjs.org/pkg-%d/-/pkg-%d-%d.0.0.tgz", i, i, i),
			"integrity": "sha512-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=",
		}
	}
	out, _ := json.Marshal(map[string]any{"packages": pkgs})
	return out
}

func buildYarnLock(n int) []byte {
	var b strings.Builder
	b.WriteString("# yarn lockfile v1\n\n")
	for i := range n {
		fmt.Fprintf(&b, "\"pkg-%d@^%d.0.0\":\n  version \"%d.%d.%d\"\n  resolved \"https://r.example/pkg-%d\"\n  integrity sha512-AAA=\n\n",
			i, i%10, i%10, i%100, i, i)
	}
	return []byte(b.String())
}

func buildPnpmLock(n int) []byte {
	var b strings.Builder
	b.WriteString("lockfileVersion: '6.0'\n\ndependencies:\n")
	for i := range n {
		fmt.Fprintf(&b, "  'pkg-%d': %d.%d.%d\n", i, i%10, i%100, i)
	}
	return []byte(b.String())
}

func buildCargoLock(n int) []byte {
	var b strings.Builder
	b.WriteString("# This file is automatically @generated by Cargo.\n\n")
	for i := range n {
		fmt.Fprintf(&b, "[[package]]\nname = \"crate-%d\"\nversion = \"%d.%d.%d\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\n\n",
			i, i%10, i%100, i)
	}
	return []byte(b.String())
}

// ---------- benchmarks ----------

func BenchmarkParsePackageLock(b *testing.B) {
	for _, n := range []int{100, 1000, 5000} {
		data := buildPackageLockJSON(n)
		b.Run(fmt.Sprintf("n=%d/bytes=%d", n, len(data)), func(b *testing.B) {
			b.SetBytes(int64(len(data)))
			b.ReportAllocs()
			for range b.N {
				parsePackageLock(data)
			}
		})
	}
}

